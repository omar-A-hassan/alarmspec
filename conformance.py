"""White-box conformance test: alarm.c against AlarmSystem.tla.

TLC writes the full state graph of the model. This test loads each reachable state into
the C implementation and fires each event. In each state, the successor states of the
C code must be equal to the successor states of the model. Thus the code makes no
transition that the model forbids, and it makes each transition that the model allows.

alarm.toml describes the alarm system. ALARM_CONFIG can name a different file.

Run: JAVA=/path/to/java uv run --no-project python conformance.py
"""
import ctypes
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
JAVA = os.environ.get("JAVA", "java")
CONFIG = Path(os.environ.get("ALARM_CONFIG", HERE / "alarm.toml"))
JAR = HERE / "tools" / "tla2tools.jar"
# The TLA+ tools build that the verification used: TLC 2026.10.28.014557.
JAR_URL = ("https://github.com/omar-A-hassan/alarmspec/releases/download/"
           "tla2tools-2026.10.28/tla2tools.jar")
JAR_SHA256 = "fc6878c603f0fdc18b9fe3e5bf51860cb90ab5b1154e3c371660c036d6bdd63e"
RANK = {"LOW": 1, "MEDIUM": 2, "HIGH": 3}


def load_config(path):
    """The alarm system to check, from a .toml file. List order = MCIndex = C condition number."""
    cfg = tomllib.loads(path.read_text())
    conds = cfg["conditions"]
    names = [c["name"] for c in conds]
    spec = (HERE / "AlarmSystem.tla").read_text()
    for c in conds:
        bad = [k for k in c if k not in ("name", "priority", "latching", "escalating", "timed")]
        if bad or c.get("priority") not in RANK:
            sys.exit(f"{path}: condition {c.get('name')}: unknown keys {bad} or priority not HIGH/MEDIUM/LOW")
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", c["name"]) or re.search(rf"\b{c['name']}\b", spec):
            sys.exit(f"{path}: condition name {c['name']!r} must be a letter then letters, digits or _, "
                     "and not a word used in AlarmSystem.tla")
    if not 1 <= len(names) <= 32 or len(set(names)) != len(names):
        sys.exit(f"{path}: need 1 to 32 conditions with distinct names")
    if min(cfg["pause_ticks"], cfg["reminder_ticks"], cfg["escalate_ticks"]) < 1:
        sys.exit(f"{path}: every *_ticks must be at least 1")
    pick = lambda key: {c["name"] for c in conds if c.get(key)}
    return (names, [RANK[c["priority"]] for c in conds], pick("latching"), pick("escalating"),
            pick("timed"), cfg["pause_ticks"], cfg["reminder_ticks"], cfg["escalate_ticks"],
            bool(cfg["low_audible"]))


(CONDS, PRIO, LATCHING, ESCALATING, TIMED_ESCALATING,
 PAUSE_TICKS, REMINDER_TICKS, ESCALATE_TICKS, LOW_AUDIBLE) = load_config(CONFIG)
REQUIREMENTS = ["TypeOK", "Visible", "Audible", "NoStaleSignal", "LatchHolds", "LatchSounds",
                "NewHighBreaksPause", "LiveAfterBoot", "EscalatesOnTime", "ToneIsTop"]

INACT = ["NONE", "AUDIO_PAUSED", "ALARM_PAUSED", "AUDIO_OFF", "ALARM_OFF"]
SETS = ["active", "worse", "latched", "pausedSet", "acked", "lit", "sounding"]
FIELD = {"pausedSet": "paused_set"}  # model name -> C name, where they differ


class Sys(ctypes.Structure):  # mirrors alarm_sys in alarm.h
    _fields_ = [
        ("n", ctypes.c_uint8), ("prio", ctypes.c_uint8 * 32),
        ("latching", ctypes.c_uint32), ("escalating", ctypes.c_uint32),
        ("timed_escalating", ctypes.c_uint32),
        ("pause_ticks", ctypes.c_uint16), ("reminder_ticks", ctypes.c_uint16),
        ("escalate_ticks", ctypes.c_uint16), ("low_audible", ctypes.c_bool),
        ("active", ctypes.c_uint32), ("worse", ctypes.c_uint32),
        ("latched", ctypes.c_uint32), ("paused_set", ctypes.c_uint32),
        ("acked", ctypes.c_uint32), ("inact", ctypes.c_uint8), ("timer", ctypes.c_uint16),
        ("age", ctypes.c_uint16 * 32),
        ("lit", ctypes.c_uint32), ("sounding", ctypes.c_uint32),
        ("tone", ctypes.c_int8), ("reminder", ctypes.c_bool),
    ]


def mask(names):
    return sum(1 << CONDS.index(c) for c in names)


def build(tmp):
    lib = Path(tmp, "libalarm.so")
    subprocess.run(["cc", "-std=c11", "-O2", "-Wall", "-Wextra", "-Werror", "-shared", "-fPIC",
                    "-o", str(lib), str(HERE / "alarm.c")], check=True)
    lib = ctypes.CDLL(str(lib))
    assert lib.alarm_sys_size() == ctypes.sizeof(Sys), "ctypes layout differs from alarm.h"
    return lib


def write_instance(dest):
    """Write the TLC model instance for the configuration: MC.tla, MC.cfg, Recalls.cfg."""
    names = ", ".join(CONDS)
    fn = lambda pairs: " @@ ".join(f"({c} :> {v})" for c, v in pairs)
    prio = {r: p for p, r in RANK.items()}
    Path(dest, "MC.tla").write_text(f"""---- MODULE MC ----
\\* conformance.py makes this file from {CONFIG.name}. Do not edit this file.
EXTENDS AlarmSystem, TLC

CONSTANTS {names}

MCConds      == {{{names}}}
MCPriority   == {fn((c, f'"{prio[r]}"') for c, r in zip(CONDS, PRIO))}
MCLatching   == {{{", ".join(c for c in CONDS if c in LATCHING)}}}
MCEscalating == {{{", ".join(c for c in CONDS if c in ESCALATING)}}}
MCTimedEscalating == {{{", ".join(c for c in CONDS if c in TIMED_ESCALATING)}}}
MCIndex      == {fn((c, i) for i, c in enumerate(CONDS))}
====
""")
    consts = lambda low: "CONSTANTS\n" + "".join(f"    {c} = {c}\n" for c in CONDS) + f"""\
    Conds <- MCConds
    Priority <- MCPriority
    Latching <- MCLatching
    Escalating <- MCEscalating
    TimedEscalating <- MCTimedEscalating
    EscalateTicks = {ESCALATE_TICKS}
    Index <- MCIndex
    PauseTicks = {PAUSE_TICKS}
    ReminderTicks = {REMINDER_TICKS}
    LowAudible = {low}
    Fault = "NONE"
"""
    invariants = "INVARIANTS\n" + "".join(f"    {r}\n" for r in REQUIREMENTS)
    Path(dest, "MC.cfg").write_text(consts(str(LOW_AUDIBLE).upper()) + "\nSPECIFICATION Spec\n\n"
                                    + invariants + "\nPROPERTIES\n    PauseEnds\n    RemindWhileOff\n")
    Path(dest, "Recalls.cfg").write_text(consts("LOWAUDIBLE") + "    Script <- SCRIPT\n    StartActive <- STARTACTIVE\n"
                                         + "\nSPECIFICATION Replay\n\n" + invariants)


def tla_jar():
    """Path of the TLA+ tools. Downloads the verified build on first use. Stops if the file
    is a different build."""
    if not JAR.exists():
        JAR.parent.mkdir(exist_ok=True)
        part = JAR.with_suffix(".part")  # a stopped download leaves no partial jar
        urllib.request.urlretrieve(JAR_URL, part)
        part.rename(JAR)
    if hashlib.sha256(JAR.read_bytes()).hexdigest() != JAR_SHA256:
        sys.exit(f"{JAR} is not the verified TLA+ tools build (SHA-256 {JAR_SHA256}). "
                 "Delete the file. The next run downloads the verified build.")
    return JAR


def model_graph(tmp):
    """Reachable states (as dicts of model variables), successor ids, initial ids, and each
    state's successor per action, e.g. acts[s]['CondOn(h1)'], from TLC."""
    write_instance(tmp)
    shutil.copy(HERE / "AlarmSystem.tla", tmp)
    # The state graph needs only the invariants. check.sh checks the temporal properties
    # (R6, R7). On a 5-condition instance, they use most of the TLC time.
    cfg = Path(tmp, "MC.cfg")
    cfg.write_text(cfg.read_text().split("\nPROPERTIES")[0] + "\n")
    dot = Path(tmp, "graph.dot")
    run = subprocess.run([JAVA, "-XX:+UseParallelGC", "-cp", str(tla_jar()), "tlc2.TLC",
                          "-workers", "auto", "-metadir", tmp, "-dump", "dot,actionlabels", str(dot),
                          "-config", "MC.cfg", "MC.tla"], cwd=tmp, capture_output=True, text=True)
    if "No error has been found" not in run.stdout:
        sys.exit(f"TLC did not pass the model for {CONFIG}:\n" + run.stdout[-2000:])
    states, succ, inits, acts = {}, {}, [], {}
    for line in dot.read_text().splitlines():
        if m := re.match(r'(-?\d+) -> (-?\d+) \[label="(.*?)",', line):
            succ.setdefault(m[1], set()).add(m[2])
            acts.setdefault(m[1], {})[m[3].replace('\\"', '"')] = m[2]
        elif m := re.match(r'(-?\d+) \[label="(.*?)",(style|tooltip)', line):
            states[m[1]] = parse(m[2].replace('\\"', '"').replace("\\\\", "\\"))
            if m[3] == "style":
                inits.append(m[1])
    return states, succ, inits, acts


def parse(label):
    out = {}
    for var, val in re.findall(r"/\\ (\w+) = (.*?)(?:\\n|$)", label):
        if val.startswith("("):  # function, e.g. (l1 :> 0 @@ l2 :> 1)
            out[var] = {k: int(v) for k, v in re.findall(r"(\w+) :> (\d+)", val)}
        elif val.startswith("{"):
            out[var] = frozenset(x.strip() for x in val[1:-1].split(",") if x.strip())
        elif val in ("TRUE", "FALSE"):
            out[var] = val == "TRUE"
        elif val.isdigit():
            out[var] = int(val)
        else:
            out[var] = val.strip('"')
    return out


def project(st):
    """The model state as the implementation sees it (monitor variables dropped)."""
    tone = -1 if st["tone"] == "NONE" else CONDS.index(st["tone"])
    age = tuple(st["age"].get(c, 0) for c in CONDS)
    return tuple(mask(st[v]) for v in SETS) + (INACT.index(st["inact"]), st["timer"], tone, st["reminder"], age)


def show(key):
    names = lambda m: "{" + ",".join(c for i, c in enumerate(CONDS) if m >> i & 1) + "}"
    inact, timer, tone, rem, age = key[len(SETS):]
    return " ".join(f"{v}={names(x)}" for v, x in zip(SETS, key)) + \
        f" inact={INACT[inact]} timer={timer} tone={CONDS[tone] if tone >= 0 else 'NONE'} reminder={rem}" + \
        f" age={dict((c, a) for c, a in zip(CONDS, age) if a)}"


def load(s, key):
    for v, x in zip(SETS, key):
        setattr(s, FIELD.get(v, v), x)
    s.inact, s.timer, s.tone, s.reminder, age = key[len(SETS):]
    s.age[:len(age)] = age


def read(s):
    return tuple(getattr(s, FIELD.get(v, v)) for v in SETS) + \
        (s.inact, s.timer, s.tone, bool(s.reminder), tuple(s.age[:len(CONDS)]))


def events(lib):
    for c in range(len(CONDS)):
        for f in ("alarm_cond_on", "alarm_cond_off", "alarm_escalate", "alarm_ack"):
            yield f"{f}({CONDS[c]})", lambda s, f=f, c=c: getattr(lib, f)(ctypes.byref(s), c)
    for name, kind in (("alarm_pause", 1), ("alarm_pause", 2), ("alarm_off", 3), ("alarm_off", 4)):
        yield f"{name}({INACT[kind]})", lambda s, name=name, kind=kind: getattr(lib, name)(ctypes.byref(s), kind)
    for f in ("alarm_reset", "alarm_cancel", "alarm_tick", "alarm_power_cycle"):
        yield f"{f}()", lambda s, f=f: getattr(lib, f)(ctypes.byref(s))


def main():
    with tempfile.TemporaryDirectory() as tmp:
        lib = build(tmp)
        states, succ, inits, _ = model_graph(tmp)

        # One start-up per initial state: any set of conditions may already be present.
        s = Sys(n=len(CONDS), prio=(ctypes.c_uint8 * 32)(*PRIO), latching=mask(LATCHING),
                escalating=mask(ESCALATING), timed_escalating=mask(TIMED_ESCALATING),
                pause_ticks=PAUSE_TICKS, reminder_ticks=REMINDER_TICKS,
                escalate_ticks=ESCALATE_TICKS, low_audible=LOW_AUDIBLE)
        for i in inits:
            s.active = mask(states[i]["active"])
            assert lib.alarm_init(ctypes.byref(s)), "alarm_init rejected the configuration"
            if read(s) != project(states[i]):
                sys.exit(f"FAIL  initial state: C [{show(read(s))}] vs model [{show(project(states[i]))}]")

        # Successors of each implementation-visible state, per the model. Self-loops are
        # stuttering steps, which TLA+ always allows, so they are not compared.
        want = {}
        for sid, st in states.items():
            k = project(st)
            want.setdefault(k, set()).update(project(states[t]) for t in succ.get(sid, ()))
            want[k].discard(k)

        evs, bad = list(events(lib)), []
        for k, expected in want.items():
            got, how = set(), {}
            for name, fire in evs:
                load(s, k)
                if fire(s) and read(s) != k:
                    got.add(read(s))
                    how[read(s)] = name
            if got != expected:
                bad.append((k, sorted(how[x] for x in got - expected), len(expected - got)))

        print(f"{len(states)} model states ({len(inits)} initial), {len(want)} distinct implementation states, "
              f"{sum(len(v) for v in want.values())} transitions compared")
        for k, extra, missing in bad[:5]:
            print(f"FAIL  in state [{show(k)}]: C-only steps {extra}, {missing} model step(s) missing")
        print("FAIL" if bad else "PASS", f"{len(bad)} state(s) disagree")
        sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
